async def main():
    await init_db()
    now = datetime.utcnow().isoformat()

    # 导入日记
    diary_count = 0
    async with get_db() as db:
        for d in DIARIES:
            did = str(uuid.uuid4())
            created = f"{d['date']}T00:00:00"
            await db.execute(
                "INSERT INTO diary_entries (id, title, content, author, source, created_at, updated_at) VALUES (?, ?, ?, ?, ?, ?, ?)",
                (did, d["title"], d["content"], "connie", "notion", created, now),
            )
            diary_count += 1
            print(f"  diary: {d['title'][:40]}")
        await db.commit()

    # 补充记忆
    mem_count = 0
    async with get_db() as db:
        for m in NEW_MEMORIES:
            mid = str(uuid.uuid4())
            await db.execute(
                "INSERT INTO memories (id, content, tags_json, created_at, updated_at) VALUES (?, ?, ?, ?, ?)",
                (mid, m["content"], json.dumps(m["tags"], ensure_ascii=False), now, now),
            )
            mem_count += 1
            print(f"  memory: {m['content'][:50]}")
        await db.commit()

    print(f"\nDone! {diary_count} diaries + {mem_count} new memories.")


if __name__ == "__main__":
    asyncio.run(main())
